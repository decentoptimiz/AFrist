/**
  ******************************************************************************
  * @file    scope_types.h
  * @brief   示波器全局类型与常量定义（数据结构 + 标定表 + 采样参数）
  ******************************************************************************
  */
#ifndef __SCOPE_TYPES_H
#define __SCOPE_TYPES_H

#include <stdint.h>

/*---------------------------------------------------------------------------*/
/* 增益档位映射表 (依据 CD4051 控制引脚 PC0~PC3)                              */
/*---------------------------------------------------------------------------*/
typedef enum {
    GAIN_1X  = 0,   /* 反馈电阻 0Ω     */
    GAIN_11X = 1,   /* 反馈电阻 20kΩ   */
    GAIN_36X = 2    /* 反馈电阻 70kΩ   */
} GainLevel_t;

/*---------------------------------------------------------------------------*/
/* 标定数据结构 (每个通道、每个档位都需要独立标定)                             */
/*---------------------------------------------------------------------------*/
typedef struct {
    float k;        /* 斜率 (ADC码值 -> 电压)   */
    float b;        /* 截距 (偏置电压补偿)      */
} CalibParams_t;

/*---------------------------------------------------------------------------*/
/* 当前运行状态                                                                */
/*---------------------------------------------------------------------------*/
typedef struct {
    uint8_t  ch1_gain;      /* CH1 当前档位                              */
    uint8_t  ch2_gain;      /* CH2 当前档位                              */
    uint16_t t_div_idx;     /* 0:1ms/div, 1:10ms/div, 2:100ms/div       */
    uint16_t trig_level;    /* 触发电平 (ADC 码值)                      */
    uint8_t  trig_edge;     /* 0:上升沿, 1:下降沿                       */
    uint8_t  run_stop;      /* 0:STOP, 1:RUN                            */
} ScopeState_t;

/*---------------------------------------------------------------------------*/
/* 标定表: cal_table[通道号0/1][增益档位0/1/2]                                */
/* 定义位于 bsp_adc_tim.c (默认 k=1, b=0, 实际使用前用两点法实测覆盖)          */
/*---------------------------------------------------------------------------*/
#define CAL_CH_CNT    2      /* 通道数   */
#define CAL_GAIN_CNT  3      /* 档位数   */

extern CalibParams_t cal_table[CAL_CH_CNT][CAL_GAIN_CNT];

/*---------------------------------------------------------------------------*/
/* 采样缓冲与采样率参数                                                        */
/*---------------------------------------------------------------------------*/
#define ADC_BUF_SIZE    1024  /* DMA 乒乓缓冲总长度                       */
#define ADC_BUF_HALF    512   /* 半满长度                                 */

/* TIM3 触发采样率: APB1 定时器时钟 84MHz, 84MHz/(1679+1) = 50kHz           */
#define TIM3_TRGO_PSC      0
#define TIM3_TRGO_PERIOD   1679

/*---------------------------------------------------------------------------*/
/* 触发与饱和检测阈值                                                          */
/*---------------------------------------------------------------------------*/
#define TRIG_HYST          5     /* 触发迟滞值 (防噪声误触发)              */
#define ADC_SAT_THRESHOLD  3950  /* 正向饱和检测阈值 (ADC 码值)            */

#endif /* __SCOPE_TYPES_H */
